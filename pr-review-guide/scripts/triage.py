#!/usr/bin/env python3
"""Label every file in a diff so the guide knows what to read closely and what to skip.

Run inside the repo, with both commits fetched:

  python3 -I triage.py <merge-base> <pr-head>

Prints one Markdown table row per file, then line totals per kind and per bucket.
The kinds are git facts plus path heuristics; the agent confirms a skip before advising it.
"""

from __future__ import annotations

import re
import subprocess
import sys
from dataclasses import dataclass

# Table order: read sooner first.
KINDS: tuple[str, ...] = ("code", "migration", "config", "build", "test", "docs", "test-data",
                          "moved", "whitespace-only", "rename-only", "deleted", "generated")
BUCKETS: dict[str, frozenset[str]] = {
    "read closely": frozenset({"code", "migration", "config", "build"}),
    "match to behaviour": frozenset({"test", "docs", "deleted"}),
    "skim or skip": frozenset({"test-data", "moved", "whitespace-only", "rename-only", "generated"}),
}

LOCKFILES: frozenset[str] = frozenset({
    "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lockb", "bun.lock", "go.sum",
    "poetry.lock", "uv.lock", "Cargo.lock", "gradle.lockfile", "Gemfile.lock", "composer.lock",
})
GENERATED_PATH = re.compile(r"(^|/)(generated|gen|build|target|dist|node_modules|__generated__)/"
                            r"|\.pb\.go$|_pb2(_grpc)?\.py$|\.g\.dart$|\.min\.(js|css)$|\.snap$")
GENERATED_HEADER = re.compile(r"@generated|do not edit|auto-?generated|code generated by", re.I)
DOCS_PATH = re.compile(r"\.(md|mdx|rst|adoc)$|(^|/)docs?/", re.I)
TEST_PATH = re.compile(r"(^|/)(src/test|tests?|__tests__|spec|testdata|fixtures?)/|Tests?\.java$|IT\.java$"
                       r"|_test\.(go|py)$|(^|/)test_[^/]+\.py$|\.(test|spec)\.[jt]sx?$")
DATA_FILE = re.compile(r"\.(csv|tsv|json|jsonl|xml|ya?ml|txt|sql|html|snap)$", re.I)
MIGRATION_PATH = re.compile(r"(^|/)(migrations?|db/migration|flyway|liquibase|changelog)/|\.sql$", re.I)
BUILD_PATH = re.compile(r"(^|/)(pom\.xml|build\.gradle(\.kts)?|settings\.gradle(\.kts)?|package\.json|go\.mod"
                        r"|pyproject\.toml|requirements[^/]*\.txt|Dockerfile[^/]*|Makefile|Jenkinsfile)$"
                        r"|(^|/)\.github/workflows/")
CONFIG_PATH = re.compile(r"\.(ya?ml|properties|toml|ini|conf|json|xml|hcl|tf)$", re.I)

ANSI = re.compile(r"\x1b\[[0-9;]*m")
MOVED = "\x1b[5m"  # blink: the colour we give moved lines below, used by nothing else


@dataclass
class FileChange:
    path: str
    status: str
    old_path: str | None = None
    added: int = 0
    removed: int = 0
    moved: int = 0
    binary: bool = False
    kind: str = "code"


def git(*args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", *args], capture_output=True, text=True, check=check, errors="replace")


def read_changes(base: str, head: str) -> dict[str, FileChange]:
    """Status from --name-status, line counts from --numstat; -z keeps odd paths intact."""
    changes: dict[str, FileChange] = {}
    fields = git("diff", "-M", "-C", "--name-status", "-z", base, head).stdout.split("\0")
    i = 0
    while i < len(fields) and fields[i]:
        status = fields[i]
        if status[0] in "RC":  # rename/copy: status, old path, new path
            change = FileChange(path=fields[i + 2], status=status, old_path=fields[i + 1])
            i += 3
        else:
            change = FileChange(path=fields[i + 1], status=status)
            i += 2
        changes[change.path] = change

    fields = git("diff", "-M", "-C", "--numstat", "-z", base, head).stdout.split("\0")
    i = 0
    while i < len(fields) and fields[i]:
        added, removed, path = fields[i].split("\t", 2)
        if path == "":  # rename/copy: old and new paths follow as their own fields
            path = fields[i + 2]
            i += 3
        else:
            i += 1
        change = changes[path]
        change.binary = added == "-"
        change.added = 0 if change.binary else int(added)
        change.removed = 0 if change.binary else int(removed)
    return changes


def count_moved(base: str, head: str, changes: dict[str, FileChange]) -> None:
    """Git colours lines cut from one place and pasted in another, across files too."""
    diff = git("-c", "color.diff.oldMoved=blink", "-c", "color.diff.newMoved=blink",
               "diff", "-M", "-C", "-U0", "--color=always", "--color-moved=blocks",
               "--color-moved-ws=allow-indentation-change", base, head).stdout
    current: FileChange | None = None
    for raw in diff.splitlines():
        line = ANSI.sub("", raw)
        if line.startswith("diff --git"):
            current = None
        elif line.startswith("+++ b/"):
            current = changes.get(line[6:])
        elif current is not None and raw.startswith(MOVED):
            current.moved += 1


def is_generated(change: FileChange, head: str) -> bool:
    if change.path.rsplit("/", 1)[-1] in LOCKFILES or GENERATED_PATH.search(change.path):
        return True
    attr = git("check-attr", "--source", head, "linguist-generated", "--", change.path, check=False).stdout
    if attr.strip().endswith((": true", ": set")):
        return True
    if change.status.startswith("D") or change.binary:
        return False
    top = git("show", f"{head}:{change.path}", check=False).stdout.splitlines()[:5]
    return bool(GENERATED_HEADER.search("\n".join(top)))


def classify(change: FileChange, base: str, head: str) -> str:
    churn = change.added + change.removed
    if is_generated(change, head):
        return "generated"
    if change.status.startswith("D"):
        return "deleted"
    if change.status in ("R100", "C100"):
        return "rename-only"
    if change.status.startswith("M") and churn and not change.binary:
        if git("diff", "-w", "--ignore-blank-lines", "--quiet", base, head, "--", change.path,
               check=False).returncode == 0:
            return "whitespace-only"
    if churn >= 10 and change.moved / churn >= 0.8:
        return "moved"
    if DOCS_PATH.search(change.path):
        return "docs"
    if TEST_PATH.search(change.path):
        return "test-data" if DATA_FILE.search(change.path) else "test"
    if MIGRATION_PATH.search(change.path):
        return "migration"
    if BUILD_PATH.search(change.path):
        return "build"
    if CONFIG_PATH.search(change.path):
        return "config"
    return "code"


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit("usage: triage.py <merge-base> <pr-head>")
    base, head = sys.argv[1], sys.argv[2]
    changes = read_changes(base, head)
    count_moved(base, head, changes)
    for change in changes.values():
        change.kind = classify(change, base, head)

    rows = sorted(changes.values(), key=lambda c: (KINDS.index(c.kind), -(c.added + c.removed)))
    print("| kind | status | file | + | - | moved |")
    print("| --- | --- | --- | --- | --- | --- |")
    for c in rows:
        name = f"{c.old_path} → {c.path}" if c.old_path else c.path
        added, removed = ("bin", "bin") if c.binary else (c.added, c.removed)
        print(f"| {c.kind} | {c.status} | `{name}` | {added} | {removed} | {c.moved} |")

    lines_by_kind: dict[str, int] = {}
    files_by_kind: dict[str, int] = {}
    for c in changes.values():
        lines_by_kind[c.kind] = lines_by_kind.get(c.kind, 0) + c.added + c.removed
        files_by_kind[c.kind] = files_by_kind.get(c.kind, 0) + 1
    print()
    for kind in (k for k in KINDS if k in files_by_kind):
        print(f"{kind}: {files_by_kind[kind]} files, {lines_by_kind[kind]} changed lines")
    print()
    every = sum(lines_by_kind.values())
    for bucket, kinds in BUCKETS.items():
        lines = sum(lines_by_kind.get(k, 0) for k in kinds)
        files = sum(files_by_kind.get(k, 0) for k in kinds)
        print(f"{bucket} ({', '.join(k for k in KINDS if k in kinds)}): {lines} of {every} lines in {files} files")


if __name__ == "__main__":
    main()
